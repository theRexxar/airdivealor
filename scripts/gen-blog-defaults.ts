/**
 * One-off: turns the Blog page text, categories and stories (lib/blog-data.ts) into CMS content,
 * written to lib/cms/blog-defaults.ts. Used by the seed and as fallback.
 */
import { writeFileSync } from "node:fs";
import type { BlogContent, BodyBlock, CategoryContent, PostContent } from "../lib/cms/blog-cms-types";
import { CATS, POSTS } from "../lib/blog-data";
import type { Block } from "../lib/blog-types";
import { toId } from "../lib/i18n";
import { SOCIAL } from "../lib/site";

const L = (en: string) => ({ en, id: en ? toId(en) : "" });
const T = (en = "", id = "") => ({ en, id });
const M = (url: string) => ({ mediaId: null, url });

const page: BlogContent = {
  seo: {
    title: { en: "Blog | Air Dive Alor", id: "Blog | Air Dive Alor" },
    description: {
      en: "Stories from Air Dive Alor: marine life, the best time to dive, our boats and life in Alor Kecil village.",
      id: "Cerita dari Air Dive Alor: kehidupan laut, waktu terbaik untuk menyelam, perahu kami, dan kehidupan di desa Alor Kecil.",
    },
    ogImage: M(""),
  },
  post: {
    ctaTitle: L("Want to see it for yourself?"),
    ctaText: L("Tell us your dates. We will plan the dives and the stay."),
    ctaLabel: L("Plan your dive"),
    ctaMessage: 'Hi Air Dive Alor, I read "{title}" and would like to plan a dive trip.',
    moreTitle: L("More stories"),
    moreLabel: L("See all stories"),
    sourceNote: L("We are still moving this story from our old blog."),
    sourceLink: L("Read the full story on airdivealor.com"),
  },
  hero: { featured: "", eyebrow: L("Blog · Latest story"), buttonLabel: L("Read the story") },
  stories: {
    eyebrow: L("Stories"),
    title: L("Stories from Alor Kecil."),
    lead: L("News from the dive center, the reef and the village, written by our team."),
    allLabel: L("All"),
    pageSize: 9,
    cardLabel: L("Read story"),
  },
  cta: {
    title: L("Follow our dives."),
    text: L("More photos and videos from Alor, from our team and our guests."),
    primaryLabel: L("Follow on Instagram"),
    primaryUrl: SOCIAL.instagram,
    secondaryLabel: L("Plan your dive"),
    secondaryMessage: "Hi Air Dive Alor, I would like to plan a dive trip.",
  },
};

const categories: CategoryContent[] = Object.entries(CATS).map(([slug, [en, id]]) => ({ slug, name: T(en, id) }));

const block = (b: Block): BodyBlock | null => {
  switch (b.t) {
    case "p":
    case "h":
      return { type: b.t, text: T(b.en, b.id) };
    case "img":
      return { type: "img", photo: M(b.src), caption: T(b.en, b.id) };
    case "gallery":
      return { type: "gallery", items: b.items.map((g) => ({ photo: M(g.src), caption: T(g.en, g.id) })) };
    case "list":
      return { type: "list", items: b.items.map(([en, id]) => ({ text: T(en, id) })) };
    case "quote":
      return { type: "quote", text: T(b.en, b.id), cite: b.cite };
    case "facts":
      return { type: "facts", items: b.items.map(([le, li, ve, vi]) => ({ label: T(le, li), value: T(ve, vi) })) };
    case "link":
      return { type: "link", label: T(b.en, b.id), href: b.href };
    case "source":
      return null;
  }
};

const posts: PostContent[] = POSTS.map((p) => ({
  slug: p.slug,
  title: T(p.title, p.titleId),
  excerpt: T(p.excerpt, p.excerptId),
  date: p.date,
  category: p.cat,
  author: T(p.author[0], p.author[1]),
  initials: p.author[2],
  cover: M(p.cover),
  body: (p.body ?? []).map(block).filter((b): b is BodyBlock => !!b),
  source: p.source ?? "",
}));

const out = `/* Generated by scripts/gen-blog-defaults.ts. Built-in Blog content: seed data and fallback. */
import type { BlogContent, CategoryContent, PostContent } from "./blog-cms-types";

export const BLOG_DEFAULTS: BlogContent = ${JSON.stringify(page, null, 1)};

export const CATEGORIES_DEFAULTS: CategoryContent[] = ${JSON.stringify(categories, null, 1)};

export const POSTS_DEFAULTS: PostContent[] = ${JSON.stringify(posts, null, 1)};
`;
writeFileSync("lib/cms/blog-defaults.ts", out);
console.info(`wrote lib/cms/blog-defaults.ts (${posts.length} stories, ${categories.length} categories)`);
