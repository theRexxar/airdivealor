/**
 * One-off: turns the Dive sites page text and the 33 dive sites (lib/sites-data.ts) into CMS content
 * (English + Indonesian), written to lib/cms/dive-sites-defaults.ts. Used by the seed and as fallback.
 */
import { writeFileSync } from "node:fs";
import type { DiveSitesContent, SiteContent } from "../lib/cms/dive-sites-types";
import { toId } from "../lib/i18n";
import { SITES } from "../lib/sites-data";

const L = (en: string) => ({ en, id: en ? toId(en) : "" });
const M = (url: string) => ({ mediaId: null, url });

const page: DiveSitesContent = {
  seo: {
    title: L("Dive sites | Air Dive Alor"),
    description: L("33 dive sites around Alor, Pantar and Pura: walls, pinnacles, caverns and muck bays, each with a full site guide."),
    ogImage: M("/sites/don-tupa.jpg"),
  },
  guide: {
    typicalNote: L("Times, visibility and temperature are typical ranges, not a promise."),
    safetyNote: L("Conditions change with the tide. Your guide checks the current on the day and may switch sites to keep the dive safe."),
    draftNote: L("Notes compiled from public dive guides. Our team is still checking the details."),
    ctaTitle: L("Dive this site with us"),
    ctaText: L("Add it to your trip and we plan the day around the tide."),
    bookLabel: L("Book this dive"),
    bookMessage: "Hi Air Dive Alor, I would like to dive {site}.",
  },
  hero: {
    eyebrow: L("Dive sites · Alor and Pantar"),
    title: L("Pick a site. See what lives there."),
    lead: L("Walls, pinnacles, caverns and muck bays around Alor, Pantar and Pura. Open any site for its full guide."),
    image: M("/sites/don-tupa.jpg"),
  },
  highlights: {
    items: [
      ["flower-2", "Healthy reefs", "Hard and soft coral cover most sites, from the shallows down the wall."],
      ["mountain", "Walls, pinnacles and sand", "Steep walls, pinnacles that break the surface, overhangs and dark sandy bays."],
      ["waves", "Currents, planned by tide", "The Pantar Strait moves a lot of water. We time each dive to the tide so the current works for you."],
      ["fish", "Big fish, with luck", "Sharks, eagle rays and the odd thresher pass by. They are a bonus, never a promise."],
      ["search", "Muck and macro", "Rhinopias, frogfish, pygmy seahorses and nudibranchs live in the bays."],
      ["eye", "Clear water", "Most reef sites see 15 to 30 m. Bay sites are lower but full of small life."],
    ].map(([icon, title, text]) => ({ icon, title: L(title), text: L(text) })),
  },
  list: {
    eyebrow: L("01 · All sites"),
    title: L("Our regular dive sites."),
    pageSize: 9,
    filters: [
      ["All", ""],
      ["Walls", "Wall, Drop-off"],
      ["Muck and macro", "Muck, Macro"],
      ["Reefs and slopes", "Reef, slope"],
      ["Pinnacles and drift", "Pinnacle, Drift, Blue"],
      ["Caves", "Cave, Swim"],
    ].map(([label, match]) => ({ label: L(label), match })),
    note: L("We choose sites on the day, based on tide, current and weather. Each guide shows typical conditions, not a promise."),
  },
  cta: {
    title: L("Not sure which site suits you?"),
    text: L("Tell us your level and what you hope to see. We plan your dive days around the tide."),
    primaryLabel: L("Ask on WhatsApp"),
    primaryMessage: "Hi Air Dive Alor, which dive sites would suit me?",
    secondaryLabel: L("See prices"),
    secondaryUrl: "/#b-prices",
  },
};

const sites: SiteContent[] = SITES.map((s) => ({
  slug: s.slug,
  name: s.name,
  aka: s.aka,
  area: L(s.area || "Alor"),
  type: L(s.type),
  depth: s.depth,
  level: L(s.level),
  current: L(s.current),
  vis: s.vis,
  temp: s.temp,
  photo: M(s.photo),
  gallery: s.gallery.map((g) => ({ photo: M(g) })),
  diveTypes: s.diveTypes.map((d) => ({ label: L(d) })),
  intro: L(s.intro),
  topo: L(s.topo),
  aboutTopo: L(s.about?.[0] ?? ""),
  aboutLife: L(s.about?.[1] ?? ""),
  see: s.see.map((x) => ({ name: L(x) })),
  boatTime: L(s.access),
  entry: L(s.entry),
  minLevel: L(s.minLevel),
  hazards: L(s.hazards),
  bestTime: L(s.best),
  tips: s.tips.map((x) => ({ text: L(x) })),
  unverified: !!s.draft,
  credit: s.credit ?? "",
  creditUrl: s.creditHref ?? "",
}));

writeFileSync(
  "lib/cms/dive-sites-defaults.ts",
  `// Dive sites page content and the 33 dive site guides as CMS values (EN + ID). Generated by
// scripts/gen-dive-sites-defaults.ts from the original build. Used to seed the CMS and as fallback content.
import type { DiveSitesContent, SiteContent } from "./dive-sites-types";

export const DIVE_SITES_DEFAULTS: DiveSitesContent = ${JSON.stringify(page, null, 1)};

export const SITES_DEFAULTS: SiteContent[] = ${JSON.stringify(sites, null, 1)};
`,
);
