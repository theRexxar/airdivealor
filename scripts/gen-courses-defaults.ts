/**
 * One-off: turns the Dive courses page text and the 12 courses (lib/courses-data.ts) into CMS content
 * (English + Indonesian), written to lib/cms/courses-defaults.ts. Used by the seed and as fallback.
 */
import { writeFileSync } from "node:fs";
import type { CourseContent, CoursesContent } from "../lib/cms/courses-types";
import { COURSES, DETAILS } from "../lib/courses-data";
import { toId } from "../lib/i18n";
import { waLink } from "../lib/site";

const L = (en: string) => ({ en, id: en ? toId(en) : "" });
const M = (url: string) => ({ mediaId: null, url });
const lines = (rows: string[]) => rows.map((t) => ({ text: L(t) }));

const page: CoursesContent = {
  seo: {
    title: { en: "Dive courses | Air Dive Alor", id: "Kursus selam | Air Dive Alor" },
    description: L("SDI and TDI dive courses in Alor, from Open Water to Divemaster and technical diving. Every package includes your stay, three meals a day, gear and airport transfers."),
    ogImage: M(""),
  },
  detail: {
    bookMessage: "Hi Air Dive Alor, I would like to book the {course} ({price}).",
    bookLabel: L("Book course"),
    includedLead: L("The package price covers your training, stay, food and transfers. You only need to get to Alor."),
    notIncluded: lines(DETAILS.notIncluded),
    medical: L("Fill in the diver medical form. Some answers need a doctor's sign-off before you dive."),
    insurance: L("Dive insurance is required for every course."),
    flying: L("No diving 24 hours before your flight out."),
    reqNote: L("Requirements follow SDI and TDI standards. Your instructor confirms your plan before the course starts."),
    ctaTitle: L("Ready to start?"),
    ctaText: L("Send us your dates on WhatsApp. We reply within the hour, 7am to 9pm WITA."),
    ctaLabel: L("Book this course"),
  },
  hero: {
    eyebrow: L("Dive courses · SDI and TDI"),
    title: L("Learn to dive in Alor."),
    lead: L(
      "From your first breath underwater to Divemaster. Every package includes your stay, three meals a day, gear and airport transfers. Ask us about group rates with a private boat.",
    ),
    logos: [
      { image: M("https://airdivealor.com/public/img/sdi-logo-new.png"), alt: "SDI certified" },
      { image: M("https://airdivealor.com/public/img/TDI-Logo.png"), alt: "TDI certified" },
    ],
  },
  list: {
    filters: [["All", ""], ...["Beginner", "Advanced", "Specialty", "Professional", "Technical", "Custom"].map((l) => [l, l])].map(([label, level]) => ({ label: L(label), level })),
    moreLabel: L("What's included"),
    bookLabel: L("Book now"),
  },
  cta: {
    title: L("Coming as a group?"),
    text: L("Contact us for a special group rate and dive with your own private boat. We reply within the hour, 7am to 9pm WITA."),
    primaryLabel: L("Chat on WhatsApp"),
    primaryMessage: "Hi Air Dive Alor, we are a group and would like a special rate for a dive course.",
    secondaryLabel: { en: "+62 813-9550-5313", id: "+62 813-9550-5313" },
    secondaryUrl: waLink(),
  },
};

const courses: CourseContent[] = COURSES.map((c) => {
  const x = DETAILS.courses[c.id];
  return {
    slug: c.id,
    name: L(c.name),
    level: c.level,
    agency: c.id === "tdi" ? "TDI" : "SDI",
    price: c.price,
    stay: L(c.stay),
    dives: L(c.dives),
    photo: M(c.img),
    text: L(c.text),
    included: c.incl.map((item) => {
      const m = DETAILS.included[item];
      if (m) return { icon: m[0], title: L(item), text: L(m[1]) };
      if (/certificate/i.test(item)) return { icon: "award", title: L(item), text: L(DETAILS.certDetail) };
      return { icon: "check", title: L(item), text: L("") };
    }),
    days: L(x.days),
    diveCount: L(x.dives),
    depth: L(x.depth),
    age: L(x.age),
    group: L(x.group),
    prereq: L(x.prereq),
    learn: lines(x.learn),
    plan: x.plan.map(([day, title, text]) => ({ day: L(day), title: L(title), text: L(text) })),
    tips: lines(x.tips),
  };
});

const out = `/* Generated by scripts/gen-courses-defaults.ts. Built-in Dive courses content: seed data and fallback. */
import type { CourseContent, CoursesContent } from "./courses-types";

export const COURSES_PAGE_DEFAULTS: CoursesContent = ${JSON.stringify(page, null, 1)};

export const COURSES_DEFAULTS: CourseContent[] = ${JSON.stringify(courses, null, 1)};
`;
writeFileSync("lib/cms/courses-defaults.ts", out);
console.info(`wrote lib/cms/courses-defaults.ts (${courses.length} courses)`);
